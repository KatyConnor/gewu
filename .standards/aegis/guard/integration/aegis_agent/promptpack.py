# -*- coding: utf-8 -*-
"""PromptPack —— 提示词层注入（规范 6.1 防线一）

只影响意图，是最弱防线；关键约束必须由 GuardedWorkspace（防线二）
与 CI（防线三）机器强制。注入内容 = 守则 + 问题单卡 + 预算。
"""

LAWS = [
    'L1 最小变更律: diff 只服务当前问题单，禁止顺带重构、重命名、格式化',
    'L2 根因优先律: 禁止压制表象（吞异常、返回默认值、绕过或放宽校验）',
    'L3 测试神圣律: 禁止修改、删除、跳过既有测试来通过验证',
    'L4 影响面受控律: 实际 diff 必须落在方案单声明的变更清单内',
    'L5 红绿基线律: 无红基线不得实施，无绿证据不得申报完成',
    'L6 单一职责律: 一单一根因一提交一 PR',
    'L7 可回滚律: 修复须原子提交、可独立 revert',
    'L8 知情披露律: 超范围、失败、不确定、衍生问题必须即时上报',
]

_STAGE_TASK = {
    'P1': '只读探索代码库，产出根因单 RC（YAML 字段见 schema）；禁止写任何文件。',
    'P2': '基于 RC 产出修复方案单 FP（变更清单/预算/验证计划/回滚预案）。',
    'P3': '在预算内实施修复；每次写文件会经过护栏检查，违规写入会被拒绝并回滚。',
    'P4': '配合三层验证门；断言失败时优先怀疑自己的修复，而不是测试。',
    'P6': '产出教训条目: 避错规则、防错规则建议、可复用判例。',
}


def build_system_prompt(issue, level, budget=None):
    bud = budget or {}
    return '\n'.join([
        '# AEGIS V1.0 修复作业守则（注入系统提示；第 2、3、4、8 条不可删减）',
        '1. 你只处理当前问题单 %s；级别 %s。' % (issue, level),
        '2. 未取得红基线（复现证据）前，禁止写第一行修复代码。',
        '3. 测试文件只读: 修改测试预期须提交《测试缺陷认定单》并等待批准。',
        '4. 冻结清单文件禁止触碰；命中即停止并上报，不得绕行。',
        '5. 变更预算: 文件 %s 以内、行数 ±%s 以内；达 90%% 立即收尾。'
        % (bud.get('files', '-'), bud.get('lines', '-')),
        '6. 每阶段产出对应三单（RC/FP/VR），schema 不过视为阶段未完成。',
        '7. 同一问题连续 2 轮验证失败: 停止尝试，输出升级说明转人工。',
        '8. 任何超范围修改、不确定性、新发现的问题: 即时披露，禁止静默处理。',
        '',
        '## 铁律（完整版见规范第三章）',
    ] + ['%s' % l for l in LAWS])


def build_stage_prompt(stage, issue, extra=''):
    task = _STAGE_TASK.get(stage, '')
    head = '## 阶段任务（%s · 问题单 %s）\n%s' % (stage, issue, task)
    if extra:
        head += '\n' + extra
    return head
