-- 阶段 B：菜单动态权限 - menu 表 + role_menu 表 + 种子数据

-- 菜单表（树形结构，menu_type: 1目录 2菜单 3按钮）
CREATE TABLE IF NOT EXISTS menu (
    id VARCHAR(26) NOT NULL COMMENT 'ULID 主键',
    parent_id VARCHAR(26) DEFAULT NULL COMMENT '父菜单ID（NULL为顶级）',
    menu_name VARCHAR(64) NOT NULL COMMENT '菜单名称',
    menu_type TINYINT DEFAULT 2 COMMENT '1目录 2菜单 3按钮',
    path VARCHAR(128) DEFAULT NULL COMMENT '路由标识（对应前端 PageType）',
    icon VARCHAR(32) DEFAULT NULL COMMENT '图标名称（lucide 图标名）',
    sort_order INT DEFAULT 0 COMMENT '排序号',
    permission_code VARCHAR(128) DEFAULT NULL COMMENT '所需权限码（NULL表示无限制）',
    visible TINYINT DEFAULT 1 COMMENT '1可见 0隐藏',
    deleted TINYINT DEFAULT 0 COMMENT '逻辑删除',
    created_at BIGINT NOT NULL COMMENT '创建时间',
    updated_at BIGINT NOT NULL COMMENT '更新时间',
    created_by VARCHAR(26) DEFAULT NULL COMMENT '创建人',
    updated_by VARCHAR(26) DEFAULT NULL COMMENT '更新人',
    PRIMARY KEY (id),
    KEY idx_menu_parent (parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='菜单表';

-- 角色菜单关联表
CREATE TABLE IF NOT EXISTS role_menu (
    id VARCHAR(26) NOT NULL COMMENT 'ULID 主键',
    role_id VARCHAR(26) NOT NULL COMMENT '角色ID',
    menu_id VARCHAR(26) NOT NULL COMMENT '菜单ID',
    created_at BIGINT NOT NULL COMMENT '创建时间',
    created_by VARCHAR(26) DEFAULT NULL COMMENT '创建人',
    PRIMARY KEY (id),
    KEY idx_role_menu_role (role_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='角色菜单关联表';

